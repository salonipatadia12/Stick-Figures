class Entailment(unittest.TestCase):
    def test_an_unsupported_sentence_is_rewritten_and_logged(self):
        ep = episode_with({1: BACTERIA})
        judge = Judge(ok={PLAIN}, rewrites=[PLAIN])
        out = entail.check(ep, ask=judge)
        self.assertEqual(ep.beats[1].narration, PLAIN)
        self.assertEqual(out['changed'], [dict(beat=ep.beats[1].id, field='narration', was=BACTERIA, fact_ids=['s3'], why=mock.ANY,
                                               action='rewritten', now=PLAIN)])
        self.assertIn('quote: "biogenic', judge.checks()[0][1])       # checked against the fact's quote
        self.assertIn('rewritten', entail.view(out)[0])

    def test_a_rewrite_that_still_fails_drops_the_claim_and_keeps_the_beat(self):
        ep = episode_with({1: f'{BACTERIA} It took a very long time.'})
        n = len(ep.beats)
        out = entail.check(ep, ask=Judge(ok={'It took a very long time.'}, rewrites=['Oil starts with tiny ocean bacteria.']))
        self.assertEqual(ep.beats[1].narration, 'It took a very long time.')
        self.assertEqual(out['changed'][0]['action'], 'dropped')
        self.assertEqual(len(ep.beats), n)

    def test_a_beat_of_one_sentence_says_its_fact_as_written(self):
        ep = episode_with({1: BACTERIA})
        out = entail.check(ep, ask=Judge(rewrites=['Bacteria again, still.']))
        self.assertEqual(ep.beats[1].narration, S3.claim)
        self.assertEqual(out['changed'][0]['action'], 'said the fact as written')

    def test_a_beat_of_one_sentence_gets_a_line_with_no_fact_when_the_rewrite_fails(self):
        ep = episode_with({1: BACTERIA})
        out = entail.check(ep, ask=Judge(rewrites=['Oil starts with tiny ocean bacteria.', 'So where does oil really come from?']))
        self.assertEqual(ep.beats[1].narration, 'So where does oil really come from?')
        self.assertTrue(out['changed'][0]['action'].startswith('claim dropped'))

    def test_the_same_fact_is_never_said_twice(self):
        # 2026-11-14, first real run: b05, b06 and b07 all fell back to s3's claim
        ep = episode_with({1: BACTERIA, 2: 'These microbes live in oxygen-poor places.'})
        out = entail.check(ep, ask=Judge())
        self.assertEqual(ep.beats[1].narration, S3.claim)
        self.assertEqual(ep.beats[2].narration, 'These microbes live in oxygen-poor places.')
        self.assertEqual(out['changed'][1]['action'], 'not fixed (look at it)')
        self.assertIn('could not be fixed', out['notes'][0])

    def test_a_true_line_that_cites_the_wrong_fact_is_re_cited(self):
        ep = episode_with({1: 'Heat and pressure turned the remains into oil.'})
        ep.sources.append(Source(id='s6', claim='Heat and pressure turned ancient remains into crude oil.', url='https://www.eia.gov/x',
                                 quote='Heat and pressure from these layers turned the remains into what we now call crude oil.'))

        def ask(system, user, schema):
            if system in (entail.NONFACT_SYSTEM, entail.TEXT_SYSTEM):   # the other beats' lines state no fact
                return dict(states_a_fact=False, supported=True, adds=[], why='')
            if 's6:' in user:                        # checked against s3 and the fact that says heat and pressure
                return dict(states_a_fact=True, supported=True, adds=[], why='s6 says it')
            return dict(states_a_fact=True, supported=False, adds=['Heat and pressure'], why='s3 does not say heat')
        out = entail.check(ep, ask=ask)
        self.assertEqual(ep.beats[1].narration, 'Heat and pressure turned the remains into oil.')
        self.assertEqual(ep.beats[1].source_ids, ['s3', 's6'])
